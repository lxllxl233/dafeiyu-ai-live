def main():
    con = sqlite3.connect(DB)
    cur = con.cursor()
    cur.executescript(
        """
        CREATE TABLE IF NOT EXISTS memes(
          id TEXT PRIMARY KEY,
          text TEXT, category TEXT, game TEXT, tags TEXT,
          trigger TEXT, example TEXT, intensity INTEGER, cooldown INTEGER
        );
        DELETE FROM memes;
        """
    )
    for m in M:
        cur.execute(
            "INSERT INTO memes VALUES(?,?,?,?,?,?,?,?,?)",
            (m["id"], m["text"], m["category"], m["game"], ",".join(m["tags"]),
             m["trigger"], m["example"], m["intensity"], m["cooldown"]),
        )
    con.commit()
    con.close()
    JSON_OUT.write_text(json.dumps(M, ensure_ascii=False, indent=1), encoding="utf-8")
    print(json.dumps({"count": len(M), "json": str(JSON_OUT), "db": str(DB)}, ensure_ascii=False, indent=1))


if __name__ == "__main__":
    main()
