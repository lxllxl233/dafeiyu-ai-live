def main():
    con = sqlite3.connect(DB)
    cur = con.cursor()
    cur.executescript(
        """
        CREATE TABLE IF NOT EXISTS strategy_rules(
          id TEXT PRIMARY KEY,
          phase TEXT, priority INTEGER, title TEXT, rule TEXT, why TEXT, cards TEXT
        );
        DELETE FROM strategy_rules;
        """
    )
    for r in RULES:
        cur.execute(
            "INSERT INTO strategy_rules VALUES(?,?,?,?,?,?,?)",
            (r["id"], r["phase"], r["priority"], r["title"], r["rule"], r["why"], r["cards"]),
        )
    con.commit()
    con.close()
    JSON_OUT.write_text(json.dumps(RULES, ensure_ascii=False, indent=1), encoding="utf-8")
    print(json.dumps({"count": len(RULES), "json": str(JSON_OUT), "db": str(DB)}, ensure_ascii=False, indent=1))


if __name__ == "__main__":
    main()
